"""Інтерфейси проєкту.

У Python немає окремого ключового слова interface, тому інтерфейс оголошують
як абстрактний клас (ABC), що містить ЛИШЕ абстрактні методи — без полів,
без конструктора і без реалізації. Клас, який «реалізує інтерфейс»,
зобов'язаний перевизначити всі його методи, інакше Python не дасть створити
його об'єкт (TypeError).
"""

from abc import ABC, abstractmethod


class IInputSource(ABC):
    """Інтерфейс джерела введення: звідки програма бере відповіді гравця."""

    @abstractmethod
    def read(self, prompt: str = "") -> str:
        """Повертає наступну відповідь гравця."""


class IOutputSink(ABC):
    """Інтерфейс приймача виведення: куди програма пише результати гри."""

    @abstractmethod
    def write(self, text: str = "") -> None:
        """Виводить один рядок тексту."""
